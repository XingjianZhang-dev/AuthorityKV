def F(i):
    """number of fact i (raises if the fact does not exist)."""
    USED.append(i)
    return R[i]['number']


def run_json(run, name):
    """a stored summary of one run under runs/ (next to the results directory)."""
    return json.load(open(os.path.join(os.path.dirname(os.path.abspath(FD)), 'runs', run, name), encoding='utf-8'))


def FD_(i):
    USED.append(i)
    return R[i]['number'], R[i]['denominator']


def frac(i):
    n, d = FD_(i)
    return f'{n}/{d}'


def pstr(p):
    if isinstance(p, str):
        p = float(p.split('/')[0])
    if p >= 0.995:
        return '1'
    if p >= 0.001:
        s = f'{p:.3f}' if p < 0.1 else f'{p:.2f}'
        return s.lstrip('0')
    m, e = f'{p:.1e}'.split('e')
    return f'{m}{{\\times}}10^{{{int(e)}}}'


def comma(n):
    return f'{n:,}'.replace(',', '{,}')


def write(name, body):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8') as f:
        f.write('% Generated by paper/tools/gen_tables.py from the fact files under results/. Do not edit.\n' + body)


