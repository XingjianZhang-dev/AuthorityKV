"""results/RESPONSE_FACTS.jsonl (machine) + results/RESPONSE_FACTS.md (rendered): one citable number per line with
denominator, configuration label, cell, statistic and provenance. verify_facts.py recomputes every line independently.

Fact record: {"id", "statement", "number", "denominator", "label", "cell", "statistic", "provenance": {...}}
provenance types (see verify_facts.py):
  ih_count      {"run": <run dir name or stored id>, "method": ..., "ratio": ..., "field": reversal|hierarchy|benign_correct|malformed, "relation": optional}
  ih_mcnemar    {"run_a","method_a","ratio_a","run_b","method_b","ratio_b","field": authority_reversal|correct, "population": conflict|benign} -> number = p, aux n10/n01
  mixed_count   {"run","method","ratio","condition","population": gated64|all100,"task": both|triviaqa|2wikimqa,"field": attack|joint|contains|exact|f1|gen_mean}
  mixed_mcnemar {"run_a","method_a","ratio_a","run_b","method_b","ratio_b","condition","population","field": attack|joint|contains|exact}
  sys_count     {"run","method","ratio","population": all150|gated88,"field": prompt_strict|instruction_strict}
  json_value    {"file": path relative to repo, "path": "a.b[0].c"}  -> number = value at path
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import akv_common as C  # noqa: E402

FACTS = C.REPO / "results" / "RESPONSE_FACTS.jsonl"
FACTS_MD = C.REPO / "results" / "RESPONSE_FACTS.md"


def load() -> list[dict]:
    return C.read_jsonl(FACTS) if FACTS.exists() else []


def upsert(facts: list[dict]) -> None:
    cur = {f["id"]: f for f in load()}
    for f in facts:
        cur[f["id"]] = f
    rows = [cur[k] for k in sorted(cur)]
    C.write_jsonl(FACTS, rows)
    render(rows)


def render(rows: list[dict]) -> None:
    L = ["# results/RESPONSE_FACTS.md — citable numbers (one per line; recomputed independently by `review_experiments/verify_facts.py`)", "",
         f"Generated by `review_experiments/facts.py` ({C.now_iso()}). Machine-readable version: `results/RESPONSE_FACTS.jsonl`. All stored-output pairings rely on re-execution reproducing the stored token IDs exactly (140/140 serial, 140/140 concurrent).", "",
         "| id | statement | number | denominator | configuration label | cell | statistic | robustness (tie rule) | source |", "|---|---|---|---|---|---|---|---|---|"]
    for f in rows:
        prov = f.get("provenance", {})
        src = prov.get("run") or prov.get("file") or prov.get("run_b") or ""
        rb = f.get("robustness")
        rbs = "" if not rb else (f"{rb.get('label')}" + (f"; alt ({rb.get('alt_rule')}): " + ", ".join(rb.get("alt_numbers", [])) if rb.get("alt_numbers") else ""))
        L.append(f"| {f['id']} | {f['statement']} | {f['number']} | {f.get('denominator', '')} | {f.get('label', '')} | {f.get('cell', '')} | {f.get('statistic', '')} | {rbs} | `{src}` ({prov.get('type')}) |")
    FACTS_MD.write_text("\n".join(L) + "\n", encoding="utf-8")


def fact(fid: str, statement: str, number, denominator, label: str, cell: str, statistic: str, provenance: dict) -> dict:
    return {"id": fid, "statement": statement, "number": number, "denominator": denominator, "label": label, "cell": cell, "statistic": statistic, "provenance": provenance}
